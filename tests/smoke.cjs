'use strict';
const fs = require('fs'), vm=require('vm'), assert=require('node:assert/strict');
const code = fs.readFileSync(__dirname + '/../main.js', 'utf8');
const moduleMock={exports:{}};
const sandbox={module:moduleMock, require:(n)=> {assert.equal(n,'obsidian');return {Plugin:class{},PluginSettingTab:class{},Setting:class{},Notice:class{},Modal:class{},htmlToMarkdown: x=>x}; }, console, URL, Math};
vm.runInNewContext(code, sandbox, {filename:'main.js'});
const f=moduleMock.exports._internal;
function eq(a,b){assert.equal(a,b);}
const defaults={ convertMath:true,cleanTracking:true,normalizeHeadings:true,condenseBlankLines:true,enableCustomRules:false,wrapSelectedTextWithUrl:true,rules:[]};
const original = [String.raw`Inline \(E=mc^2\)`, String.raw`\[\frac{1}{2}\]`, '', '```python', 'url="https://example.com/?utm_source=KEEP"', String.raw`x=r"\(E=mc^2\)"`, '```', '', 'And [docs](https://obsidian.md/?utm_source=chatgpt&id=42) plus https://example.org/?fbclid=ABC&key=A%20B.'].join('\n');
const result=f.formatPaste(original,'',defaults);
assert.match(result,/\$E=mc\^2\$/);
assert.match(result,/\$\$\n\\frac\{1\}\{2\}\n\$\$/);
assert.match(result,/url="https:\/\/example\.com\/\?utm_source=KEEP"/);
assert.match(result,/x=r"\\\(E=mc\^2\\\)"/);
assert.match(result,/\]\(https:\/\/obsidian\.md\/\?id=42\)/);
assert.match(result,/https:\/\/example\.org\/\?key=A%20B\./);
eq(f.stripTrackingUrl('https://example.com/?id=42&utm_source=chatgpt&key=x%20y#t'),'https://example.com/?id=42&key=x%20y#t');
eq(f.stripTrackingUrl('https://example.com/?utm_medium=email'),'https://example.com/');
const codeblock='```python\nurl="https://example.com/?fbclid=REMOVE"\n```';
const rules=[{enabled:true,type:'regex',name:'dangerous',pattern:'REMOVE',replacement:'CHANGED',flags:'g',scope:'prose'}];
eq(f.applyCustomRules(codeblock,rules,{enableCustomRules:true,allowJavaScriptRules:false}),codeblock);
eq(f.applyCustomRules('outside REMOVE',rules,{enableCustomRules:true,allowJavaScriptRules:false}),'outside CHANGED');
const before=f.formatPaste('**literal** inside `foo=\\(x\\)`\n\n\n\n## **Heading**','',defaults);
assert.match(before,/`foo=\\\(x\\\)`/);
assert.match(before,/## Heading/);
assert.match(before,/\*\*literal\*\*/);
const selected=f.formatPaste('https://example.org/?utm_source=x&id=7','',defaults,{selectedText:'Paper [1]'});
eq(selected,'[Paper [1\\]](https://example.org/?id=7)');
const fn = f.normalizeRule({name:'test',enabled:true,pattern:'[a-z]+',replacement:'X',scope:'prose'});
assert.equal(fn.type,'regex');
const fenceInside=f.isInsideFence({getCursor:()=>({line:2,ch:5}),getLine:i=>['text','```python','print(1)'][i]});
assert.ok(fenceInside);
console.log('PASS 14+ smoke checks: math, protected code, link cleaning, rules, headings, selected URL, fence context');
